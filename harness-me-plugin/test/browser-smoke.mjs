// Optional local browser smoke test; never writes examples to the user's Me store.
import { chromium } from '/usr/local/lib/node_modules/openclaw/node_modules/playwright-core/index.mjs';
import { readFile, mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { MeStore } from '../lib/store.js';
import { NutstoreBackups } from '../lib/nutstore.js';
const dir = await mkdtemp(path.join(tmpdir(), 'me-browser-test-'));
const store = new MeStore({ filePath: path.join(dir, 'me.json') });
const backups = new NutstoreBackups({ directory: path.join(dir, 'nutstore-backups') });
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 1000 } });
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.exposeFunction('hostRequest', async ({op,...args}) => {
    if(op==='info')return {dataFile:store.filePath,policy:'TEST ONLY'};
    if(op==='nutstoreBackup')return backups.backup(await store.exportBackup());
    if(op==='nutstoreList')return backups.list(args);
    if(op==='nutstoreRead')return backups.read(args);
    return store[op](args);
  });
  await page.setContent(await readFile(new URL('../page.html',import.meta.url),'utf8'));
  await page.evaluate(()=>window.__meConnect(window.hostRequest));
  await page.locator('[data-tab=daily]').click();
  await page.locator('#count').filter({hasText:'共 0 条'}).waitFor();
  await page.locator('#content').fill('BROWSER TEST <script>not executable</script>');
  await page.locator('#quick button[type=submit]').click();
  await page.locator('.note').filter({hasText:'BROWSER TEST'}).waitFor();
  assert.equal((await store.search()).total,1);
  await page.locator('[data-tab=about]').click();
  await page.locator('#newProfile').click();
  await page.locator('#editContent').fill('TEST background');
  await page.locator('#editInclude').check();
  await page.locator('#editForm button[type=submit]').click();
  await page.locator('#profiles .note').filter({hasText:'TEST background'}).waitFor();
  assert.equal((await store.profileGet()).profiles.length,1);
  await page.locator('[data-tab=reviews]').click();
  await page.locator('#reviewDate').fill('2026-11-11');
  await page.locator('#reviewSummary').fill('BROWSER REVIEW 原始日记');
  await page.locator('#reviewAnalysis').fill('BROWSER REVIEW 独立分析');
  await page.locator('#reviewForm button[type=submit]').click();
  await page.locator('#reviewList').filter({hasText:'BROWSER REVIEW 原始日记'}).waitFor();
  assert.equal((await store.reviewList()).total,1);
  await page.locator('[data-tab=privacy]').click();
  await page.locator('#nutstoreBackup').click();
  await page.locator('#nutstoreStatus').filter({hasText:'备份已写入'}).waitFor();
  assert.equal((await backups.list()).backups.length,1);
  await page.locator('#nutstoreRestore').click();
  await page.locator('#chooseNutstore:not([disabled])').waitFor();
  await page.locator('#chooseNutstore').click();
  await page.locator('#restoreDialog[open]').waitFor();
  await page.locator('#confirmRestore').click();
  await page.locator('#notice').filter({hasText:'备份已合并'}).waitFor();
  assert.equal((await store.search()).total,1,'restore must not duplicate identical records');
  await page.locator('[data-tab=daily]').click();
  await page.locator('#query').fill('BROWSER TEST');
  await page.locator('#filters button[type=submit]').click();
  await page.locator('#count').filter({hasText:'共 1 条'}).waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth), 'mobile no horizontal overflow');
  assert.deepEqual(errors,[]);
  console.log('PASS real Chromium: empty state, record save, profile create, review save, search, Nutstore backup/merge restore, mobile layout. Temporary test data only.');
  const response = await page.request.get('http://127.0.0.1:51011');
  console.log('Existing GUI unauthenticated HTTP status:',response.status());
} finally { await browser.close(); }
